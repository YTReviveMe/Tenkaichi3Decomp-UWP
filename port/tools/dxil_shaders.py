#!/usr/bin/env python3
"""Compile the SDL GPU shaders for the Direct3D 12 backend."""

import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "port/src/gs/shaders"
OUT = ROOT / "port/build/gen/gs"


def tool(name):
    override = os.environ.get("BT3_" + name.upper().replace("-", "_"))
    if override:
        return override
    found = shutil.which(name)
    if found:
        return found
    if name == "dxc" and os.name == "nt":
        kits = Path(os.environ.get("ProgramFiles(x86)", "C:/Program Files (x86)")) / "Windows Kits/10/bin"
        found = sorted(kits.glob("*/x64/dxc.exe"))
        if found:
            return str(found[-1])
    raise SystemExit(f"Missing shader tool: {name}")


def run(args):
    subprocess.run(args, check=True, cwd=ROOT)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    nz = OUT / "gsnz.frag"
    nz.write_text((SRC / "gs.frag").read_text().replace("\n", "\n#define NO_FRAG_DEPTH\n", 1))
    wb = OUT / "gswb.frag"
    wb.write_text((SRC / "gs.frag").read_text().replace("\n", "\n#define NO_FRAG_DEPTH\n#define GS_BLOCK\n", 1))
    glslang = tool("glslangValidator")
    cross = tool("spirv-cross")
    dxc = tool("dxc")
    arrays = []
    for source in sorted(SRC.glob("*.*")) + [nz, wb]:
        stage = source.suffix[1:]
        if stage not in ("vert", "frag"):
            continue
        name = "k" + source.stem.capitalize() + stage.capitalize() + "Dxil"
        spirv = OUT / (source.name + ".dxil-input.spv")
        hlsl = OUT / (source.name + ".hlsl")
        dxil = OUT / (source.name + ".dxil")
        run([glslang, "-V", "-S", stage, str(source), "-o", str(spirv)])
        run([cross, str(spirv), "--hlsl", "--shader-model", "60", "--output", str(hlsl)])
        if stage == "frag":
            text = hlsl.read_text()
            text = text.replace("float4 gl_FragCoord : SV_Position;",
                                "noperspective centroid float4 gl_FragCoord : SV_Position;")
            hlsl.write_text(text)
        run([dxc, "-T", "vs_6_0" if stage == "vert" else "ps_6_0", "-E", "main", "-Fo", str(dxil), str(hlsl)])
        arrays.append(f"static const unsigned char {name}[] = {{" + ",".join(str(b) for b in dxil.read_bytes()) + "};\n")
    (OUT / "dxil_shaders.h").write_text("/* generated by port/tools/dxil_shaders.py */\n" + "".join(arrays))
    print(f"Compiled {len(arrays)} Direct3D shaders")


if __name__ == "__main__":
    main()
